// Bundles the Lucide icons the promo uses into src/icons.js (window.ICONS),
// so the page works from file:// without fetching anything.
const fs = require('fs');
const path = require('path');

const NAMES = [
  'moon', 'moon-star', 'baby', 'milk', 'soup', 'utensils', 'chart-column', 'calendar-days',
  'sparkles', 'bot', 'clock', 'timer', 'bell', 'file-spreadsheet', 'download', 'check',
  'arrow-right', 'pencil', 'notebook-pen', 'sun', 'sprout', 'heart', 'droplets', 'brain',
  'message-circle', 'trending-up', 'list-checks', 'play', 'plus', 'hand', 'bed',
  'alarm-clock', 'apple', 'smile', 'footprints', 'star', 'calendar-clock', 'leaf',
];

const dir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const out = {};
for (const name of NAMES) {
  const svg = fs.readFileSync(path.join(dir, `${name}.svg`), 'utf8');
  // keep only the inner shapes; the page wraps them in its own <svg>
  out[name] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'))
    .replace(/\s+/g, ' ').trim();
}
const banner = '// Generated by scripts/build_icons.js from lucide-static (ISC license).\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'icons.js'),
  `${banner}window.ICONS = ${JSON.stringify(out, null, 1)};\n`);
console.log(`wrote ${NAMES.length} icons`);
